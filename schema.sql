create policy "Enable insert for everyone" on "public"."jobs" as PERMISSIVE for INSERT to public with check (true);
create policy "Enable update for everyone" on "public"."jobs" as PERMISSIVE for UPDATE to public using (true);
create policy "Enable delete for everyone" on "public"."jobs" as PERMISSIVE for DELETE to public using (true);
